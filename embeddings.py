"""
embeddings.py — единая точка конфигурации модели эмбеддингов.

Почему вынесено в отдельный файл:
  • ingest.py (индексация) и rag_engine.py (поиск) ОБЯЗАНЫ использовать
    одну и ту же модель эмбеддингов. Если при индексации использовалась
    модель A, а при поиске — модель B, векторы окажутся в разных
    пространствах и поиск вернёт бессмысленные результаты.
  • Единое место = смена модели в одну строку без риска рассинхронизации.
"""

from langchain_huggingface import HuggingFaceEmbeddings

# ---------------------------------------------------------------------------
# Константа модели
# ---------------------------------------------------------------------------
# paraphrase-multilingual-MiniLM-L12-v2 выбрана по нескольким причинам:
#   1. Бесплатна и работает полностью локально — не требует API-ключей.
#   2. Поддерживает 50+ языков, включая русский — критично для учебных
#      материалов на кириллице.
#   3. Размер ~420 МБ и 12 слоёв трансформера — хороший баланс качества
#      и скорости на CPU.
#   4. Выдаёт векторы размерностью 384 — достаточно для семантического
#      поиска в небольших базах знаний.
#
# Альтернативы для лучшего качества (но медленнее):
#   • intfloat/multilingual-e5-large      (~1.2 ГБ, размерность 1024)
#   • DeepPavlov/rubert-base-cased-sentence (~700 МБ, только русский)
EMBEDDING_MODEL = "sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2"

def get_embeddings(device: str = "cpu") -> HuggingFaceEmbeddings:
    """
    Создаёт и возвращает объект эмбеддингов с фиксированной конфигурацией.

    Параметры:
        device (str): устройство для вычислений.
            • "cpu"  — работает везде, достаточно для баз до ~50 000 чанков.
            • "cuda" — требует NVIDIA GPU с установленным CUDA; ускоряет
                       индексацию в 5-10 раз при больших объёмах данных.

    Возвращает:
        HuggingFaceEmbeddings — обёртка LangChain над sentence-transformers,
        которую можно напрямую передавать в Chroma и другие векторные БД.

    Важно:
        При первом вызове модель скачивается с HuggingFace Hub (~420 МБ)
        и кешируется в ~/.cache/huggingface/. Последующие вызовы загружают
        модель из кеша мгновенно.
    """
    return HuggingFaceEmbeddings(
        model_name=EMBEDDING_MODEL,

        # device передаётся внутрь PyTorch — указывает, на каком железе
        # будет работать нейросетевая модель эмбеддингов
        model_kwargs={"device": device},

        # normalize_embeddings=True приводит каждый вектор к единичной длине
        # (L2-нормализация). Это критично при использовании косинусного
        # сходства: нормализованные векторы дают корректные значения от -1 до 1.
        # Chroma по умолчанию использует косинусное сходство, поэтому флаг
        # включён явно — без него результаты поиска могут быть нестабильными.
        encode_kwargs={"normalize_embeddings": True},
    )
