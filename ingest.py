"""
ingest.py — скрипт индексации базы знаний.

Что делает этот файл:
  1. Обходит папку data/ и загружает все документы (.txt, .pdf, .docx).
  2. Нарезает длинные тексты на перекрывающиеся фрагменты (чанки).
  3. Преобразует каждый чанк в числовой вектор (эмбеддинг) с помощью
     локальной нейросетевой модели.
  4. Сохраняет векторы в ChromaDB (папка vector_db/) для быстрого
     семантического поиска в будущем.

Когда запускать:
  • Первый раз перед стартом приложения.
  • При добавлении, изменении или удалении документов в data/.
    Перед повторным запуском обязательно удалите vector_db/:
      rm -rf vector_db/
    Иначе новые чанки добавятся поверх старых и будут дубликаты.

Типичное время работы:
  • CPU: ~1-2 минуты на 10 МБ текста.
  • GPU: в 5-10 раз быстрее.
"""

import os
import re
import glob
from functools import partial

from dotenv import load_dotenv

# DirectoryLoader — рекурсивно обходит папку и загружает файлы по маске
# TextLoader      — читает .txt файл как единый Document
# PyPDFLoader     — читает .pdf постранично, каждая страница = отдельный Document
from langchain_community.document_loaders import DirectoryLoader, TextLoader, PyPDFLoader

# RecursiveCharacterTextSplitter — нарезает текст на чанки с учётом
# естественных разделителей (абзацы → строки → пробелы → символы)
from langchain_text_splitters import RecursiveCharacterTextSplitter

# Chroma — векторная база данных, хранящая эмбеддинги и исходные тексты
from langchain_chroma import Chroma

# Document — базовый тип LangChain: page_content (текст) + metadata (словарь)
from langchain_core.documents import Document

# docx2txt — простая библиотека для извлечения текста из .docx без зависимости
# от Microsoft Word. Возвращает чистый текст, игнорируя форматирование.
import docx2txt

# Общий модуль эмбеддингов — подробнее см. embeddings.py
from embeddings import get_embeddings

# Загружаем переменные из .env (GIGACHAT_CREDENTIALS, TM_PASSWORD и др.)
# Вызов безопасен даже если .env отсутствует — просто ничего не загрузится
load_dotenv()

# ---------------------------------------------------------------------------
# Конфигурация индексации
# ---------------------------------------------------------------------------

# Папка с исходными документами — кладите сюда лекции, глоссарий, методички
DATA_DIR = "./data"
# Папка для хранения векторной базы — создаётся автоматически при первом запуске
VECTOR_DB_DIR = "./vector_db"

# CHUNK_SIZE — максимальное количество символов в одном чанке.
# Выбор значения 1000:
#   • Слишком маленькие чанки (< 300) теряют контекст — предложение может
#     оказаться разрезанным.
#   • Слишком большие (> 2000) "размывают" смысл — вектор усредняет всё
#     содержимое и становится менее точным для конкретных вопросов.
#   • 1000 символов ≈ 2-4 абзаца — хороший баланс для учебных текстов.
CHUNK_SIZE = 1000

# CHUNK_OVERLAP — количество символов, которые повторяются между соседними
# чанками. Нужно, чтобы не "разрезать" мысль, которая начинается в конце
# одного чанка и заканчивается в начале следующего.
# Правило: обычно 15-20% от CHUNK_SIZE. При 1000 символов → 200 символов.
CHUNK_OVERLAP = 200

# Инициализируем модель эмбеддингов один раз для всего скрипта
# (загрузка модели занимает ~3-5 секунд, повторная инициализация не нужна)
embeddings = get_embeddings()


# ---------------------------------------------------------------------------
# Загрузка документов
# ---------------------------------------------------------------------------

def load_documents(data_dir: str) -> list[Document]:
    """
    Загружает все поддерживаемые документы из указанной папки.
    Возвращает: Список Document-объектов из всех найденных файлов.
    """
    documents: list[Document] = []

    # --- TXT ---
    # partial позволяет зафиксировать аргумент encoding="utf-8" в классе
    # TextLoader — DirectoryLoader передаёт loader_cls как фабрику и вызывает
    # его с одним аргументом (путь к файлу), поэтому encoding нельзя передать
    # напрямую, нужен именно partial.
    TextLoaderUTF8 = partial(TextLoader, encoding="utf-8")
    txt_loader = DirectoryLoader(
        data_dir,
        glob="*.txt",            # только файлы с расширением .txt
        loader_cls=TextLoaderUTF8,
        show_progress=True,      # прогресс-бар в консоли при большом числе файлов
    )
    txt_docs = txt_loader.load()
    documents.extend(txt_docs)
    print(f"✅ Загружено .txt: {len(txt_docs)}")

    # --- PDF ---
    # PyPDFLoader извлекает текст через pypdf. 
    pdf_loader = DirectoryLoader(
        data_dir,
        glob="*.pdf",
        loader_cls=PyPDFLoader,
        show_progress=True,
    )
    pdf_docs = pdf_loader.load()
    documents.extend(pdf_docs)
    print(f"✅ Загружено .pdf: {len(pdf_docs)}")

    # --- DOCX ---
    # Используем glob для получения путей, затем docx2txt для извлечения текста.
    # docx2txt.process() возвращает весь текст документа одной строкой,
    # сохраняя переносы строк между абзацами.
    docx_files = glob.glob(os.path.join(data_dir, "*.docx"))
    for file in docx_files:
        text = docx2txt.process(file)

        # Очищаем управляющие символы (коды 0x00-0x1F кроме \n и \t),
        # которые могут встречаться в .docx и ломают JSON-сериализацию
        # при сохранении метаданных в ChromaDB.
        # re.sub заменяет все совпадения на пустую строку "".
        text = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", text)

        # Создаём Document вручную с метаданными.
        # "source" — стандартный ключ метаданных в LangChain, используется
        # при отображении источников в интерфейсе.
        documents.append(Document(page_content=text, metadata={"source": file}))
    print(f"✅ Загружено .docx: {len(docx_files)}")
    return documents

# ---------------------------------------------------------------------------
# Нарезка на чанки
# ---------------------------------------------------------------------------

def split_documents(documents: list[Document]) -> list[Document]:
    """
    Разбивает загруженные документы на небольшие перекрывающиеся фрагменты.

    RecursiveCharacterTextSplitter пробует разделить текст последовательно
    по каждому из separators, пока размер фрагмента не станет <= chunk_size.
    Порядок разделителей важен — сначала пробуем "мягкое" деление по абзацам,
    а "жёсткое" деление по символу — только в крайнем случае.

    Почему не просто split по "\n":
      Если абзац сам по себе длиннее chunk_size (например, длинный список),
      разделитель "\n" не поможет, и нужен следующий уровень — пробел или
      отдельный символ.
    """
    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=CHUNK_SIZE,
        chunk_overlap=CHUNK_OVERLAP,
        # Иерархия разделителей (от "лучшего" к "последнему resort"):
        # \n\n — пустая строка между абзацами (идеальное место для разреза)
        # \n   — конец строки (хуже, но приемлемо)
        # " "  — пробел между словами (режем слово — плохо, но лучше чем ничего)
        # ""   — любой символ (крайний случай, режет слово пополам)
        separators=["\n\n", "\n", " ", ""],
    )
    chunks = text_splitter.split_documents(documents)
    print(f"✂️  Документы разбиты на {len(chunks)} чанков")
    return chunks


# ---------------------------------------------------------------------------
# Создание векторного хранилища
# ---------------------------------------------------------------------------

def create_vector_store(chunks: list[Document], persist_dir: str) -> Chroma:
    """
    Создаёт векторное хранилище ChromaDB из готовых чанков.

    Процесс:
      1. Для каждого чанка вызывается embeddings.embed_documents() —
         локальная нейросеть преобразует текст в числовой вектор.
      2. Вектор + исходный текст + метаданные сохраняются в SQLite-файл
         внутри persist_dir.
      3. При следующем запуске приложения ChromaDB загружает уже готовые
         векторы из файла — повторная индексация не нужна.

    Параметры:
        chunks      — список чанков после split_documents()
        persist_dir — путь к папке для хранения БД (создаётся если не существует)

    Возвращает:
        Объект Chroma, готовый к поиску (но в ingest.py он не используется дальше).
    """
    vector_store = Chroma.from_documents(
        documents=chunks,
        embedding=embeddings,
        persist_directory=persist_dir,
        # collection_name — логическое имя коллекции внутри ChromaDB.
        # Должно совпадать с именем в rag_engine.py, иначе поиск будет
        # обращаться к пустой или несуществующей коллекции!
        collection_name="machinery_technology",
    )
    print(f"💾 Векторное хранилище сохранено в {persist_dir}")
    return vector_store


# ---------------------------------------------------------------------------
# Точка входа
# ---------------------------------------------------------------------------

def main() -> None:
    """
    Оркестрирует полный пайплайн индексации: загрузка → нарезка → сохранение.
    Все три этапа выполняются последовательно.
    """
    print("🚀 Начинаем индексацию базы знаний...")

    docs = load_documents(DATA_DIR)
    # Проверка: если data/ пуста или файлы неподдерживаемого формата —
    # прерываем выполнение с понятным сообщением вместо тихого создания
    # пустой базы, с которой приложение будет работать, но всегда отвечать
    # "информации нет".
    if not docs:
        print("❌ Не найдено документов для индексации!")
        return

    chunks = split_documents(docs)
    create_vector_store(chunks, VECTOR_DB_DIR)
    print("🎉 Индексация завершена успешно!")

# Стандартный Python-паттерн: код внутри if __name__ == "__main__" выполняется
# только при прямом запуске скрипта (python ingest.py), но НЕ при импорте
# модуля другими скриптами. Это позволяет безопасно импортировать функции
# load_documents, split_documents и т.д. без побочных эффектов.
if __name__ == "__main__":
    main()
